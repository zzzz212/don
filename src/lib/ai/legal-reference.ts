//     visible quality signal in the report.
//   • With this block in the system prompt, the model has a fixed
//     anchor. Article numbers it cites can be checked against the list
//     it just read. Hallucinated articles become rare.
//   • The block is large (~3-4k tokens) but it's CONSTANT across every
//     analyze call. Anthropic prompt caching keeps the cost of repeat
