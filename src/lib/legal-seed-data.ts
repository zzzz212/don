export async function seedLegalKnowledge(prisma: any) {
  const existing = await prisma.legalKnowledge.count();

  if (existing > 0) {
    console.log("Legal knowledge already seeded, skipping...");
    return;
  }

  console.log("Seeding legal knowledge...");

  for (const item of legalSeedData) {
    try {
      await prisma.legalKnowledge.create({
        data: item,
      });
      console.log(`Created: ${item.code}`);
    } catch (error) {
      console.error(`Error creating ${item.code}:`, error);
    }
  }

  console.log("Legal knowledge seeded successfully");
}
