// Reusable contract sections with proper Russian grammar for both
// "Договор" (m) and "Соглашение" (n).

export type DealKind = "Договор" | "Соглашение";

interface DealForms {
  nom: string;          // Договор / Соглашение
  gen: string;          // Договора / Соглашения
  dat: string;          // Договору / Соглашению
  ins: string;          // Договором / Соглашением
  prep: string;         // Договоре / Соглашении
  thisNom: string;      // настоящий / настоящее
  thisGen: string;      // настоящего / настоящего
  thisDat: string;      // настоящему / настоящему
  thisIns: string;      // настоящим / настоящим
  thisPrep: string;     // настоящем / настоящем
  composedAdj: string;  // составлен / составлено  (predicate adj.)
  enteredVerb: string;  // вступает / вступает (same)
  signed: string;       // подписан / подписано
}

const DEAL_FORMS: Record<DealKind, DealForms> = {
  Договор: {
    nom: "Договор", gen: "Договора", dat: "Договору", ins: "Договором", prep: "Договоре",
    thisNom: "настоящий", thisGen: "настоящего", thisDat: "настоящему",
    thisIns: "настоящим", thisPrep: "настоящем",
    composedAdj: "составлен", enteredVerb: "вступает", signed: "подписан",
  },
  Соглашение: {
    nom: "Соглашение", gen: "Соглашения", dat: "Соглашению", ins: "Соглашением", prep: "Соглашении",
    thisNom: "настоящее", thisGen: "настоящего", thisDat: "настоящему",
    thisIns: "настоящим", thisPrep: "настоящем",
    composedAdj: "составлено", enteredVerb: "вступает", signed: "подписано",
  },
};

const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

export function forceMajeure(sectionNum: number, deal: DealKind = "Договор"): string {
  const f = DEAL_FORMS[deal];
  return `${sectionNum}. ФОРС-МАЖОР

${sectionNum}.1. Стороны освобождаются от ответственности за частичное или полное неисполнение обязательств по ${f.thisDat} ${f.dat}, если оно явилось следствием обстоятельств непреодолимой силы, возникших после заключения ${f.gen} в результате событий чрезвычайного характера, которые Стороны не могли предвидеть и предотвратить разумными мерами (землетрясения, наводнения, пожары, военные действия, эпидемии, акты органов государственной власти).

${sectionNum}.2. Сторона, для которой создалась невозможность исполнения обязательств, обязана не позднее 10 (десяти) календарных дней с момента наступления обстоятельств письменно известить об этом другую Сторону с приложением подтверждающих документов, выданных уполномоченным органом (Торгово-промышленной палатой РФ).

${sectionNum}.3. Если обстоятельства непреодолимой силы продолжаются более 2 (двух) месяцев подряд, каждая из Сторон вправе расторгнуть ${f.nom} в одностороннем внесудебном порядке без каких-либо штрафных санкций.`;
}

export function disputeResolution(sectionNum: number, deal: DealKind = "Договор"): string {
  const f = DEAL_FORMS[deal];
  return `${sectionNum}. ПОРЯДОК РАЗРЕШЕНИЯ СПОРОВ

${sectionNum}.1. Все споры и разногласия, возникающие из ${f.thisGen} ${f.gen} или в связи с ним, Стороны разрешают путём переговоров.

${sectionNum}.2. Претензионный порядок урегулирования споров обязателен. Срок рассмотрения претензии — 30 (тридцать) календарных дней с момента её получения.

${sectionNum}.3. При невозможности урегулирования спора в досудебном порядке спор подлежит рассмотрению в Арбитражном суде по месту нахождения ответчика в соответствии с законодательством Российской Федерации.`;
}

export function termination(sectionNum: number, deal: DealKind = "Договор"): string {
  const f = DEAL_FORMS[deal];
  return `${sectionNum}. ИЗМЕНЕНИЕ И РАСТОРЖЕНИЕ ${f.gen.toUpperCase()}

${sectionNum}.1. ${cap(f.thisNom)} ${f.nom} может быть изменён или расторгнут по соглашению Сторон, оформленному в письменной форме и подписанному обеими Сторонами.

${sectionNum}.2. Каждая из Сторон вправе расторгнуть ${f.nom} в одностороннем порядке в случаях, предусмотренных законодательством Российской Федерации, направив другой Стороне письменное уведомление не менее чем за 30 (тридцать) календарных дней до предполагаемой даты расторжения.

${sectionNum}.3. Расторжение ${f.gen} не освобождает Стороны от ответственности за нарушение обязательств, возникших до момента расторжения.`;
}

export function finalProvisions(sectionNum: number, deal: DealKind = "Договор"): string {
  const f = DEAL_FORMS[deal];
  return `${sectionNum}. ЗАКЛЮЧИТЕЛЬНЫЕ ПОЛОЖЕНИЯ

${sectionNum}.1. ${cap(f.thisNom)} ${f.nom} ${f.enteredVerb} в силу с момента его подписания обеими Сторонами и действует до полного исполнения Сторонами своих обязательств.

${sectionNum}.2. Все изменения и дополнения к ${f.thisDat} ${f.dat} действительны при условии их совершения в письменной форме и подписания обеими Сторонами.

${sectionNum}.3. Во всём, что не предусмотрено ${f.thisIns} ${f.ins}, Стороны руководствуются действующим законодательством Российской Федерации.

${sectionNum}.4. ${cap(f.thisNom)} ${f.nom} ${f.composedAdj} в двух экземплярах, имеющих равную юридическую силу, по одному экземпляру для каждой из Сторон.

${sectionNum}.5. Уведомления и сообщения, направленные одной Стороной другой, считаются полученными по истечении 5 (пяти) календарных дней с момента отправки заказным письмом с уведомлением о вручении или в день фактического вручения.`;
}

export function confidentiality(sectionNum: number, deal: DealKind = "Договор"): string {
  const f = DEAL_FORMS[deal];
  return `${sectionNum}. КОНФИДЕНЦИАЛЬНОСТЬ

${sectionNum}.1. Стороны обязуются сохранять в тайне информацию, полученную в ходе исполнения ${f.thisGen} ${f.gen}, в том числе сведения о коммерческой деятельности, финансовом положении, технических разработках и контрагентах другой Стороны.

${sectionNum}.2. Обязательство о конфиденциальности действует в течение всего срока действия ${f.gen} и в течение 3 (трёх) лет после его прекращения.

${sectionNum}.3. За нарушение обязательства о конфиденциальности виновная Сторона возмещает другой Стороне причинённые убытки в полном объёме.`;
}

export function signatureBlock(role1: string, party1: string, role2: string, party2: string): string {
  const padTo = (s: string, len: number) => s + " ".repeat(Math.max(0, len - s.length));
  return `РЕКВИЗИТЫ И ПОДПИСИ СТОРОН

${padTo(`${role1}:`, 45)}${role2}:
${padTo(party1 || "_______________________", 45)}${party2 || "_______________________"}

Адрес: ____________________________          Адрес: ____________________________
ИНН: ______________________________          ИНН: ______________________________
КПП: ______________________________          КПП: ______________________________
ОГРН: _____________________________          ОГРН: _____________________________
Р/с: ______________________________          Р/с: ______________________________
Банк: _____________________________          Банк: _____________________________
БИК: ______________________________          БИК: ______________________________
К/с: ______________________________          К/с: ______________________________

________________ / ____________ /          ________________ / ____________ /
       (подпись)       (Ф.И.О.)                   (подпись)       (Ф.И.О.)

           М.П.                                       М.П.`;
}

export function header(title: string, today: string, contractNum?: string): string {
  const num = contractNum ? ` № ${contractNum}` : " № _____";
  return `${title.toUpperCase()}${num}

г. Москва                                                    ${today}
`;
}

export function preamble(
  party1: string,
  inn1: string,
  role1: string,
  party2: string,
  inn2: string,
  role2: string,
  deal: DealKind = "Договор"
): string {
  const f = DEAL_FORMS[deal];
  return `${party1 || "_______________"}, ИНН ${inn1 || "_______________"}, в лице руководителя, действующего на основании Устава, именуемое в дальнейшем «${role1}», с одной стороны, и

${party2 || "_______________"}, ИНН ${inn2 || "_______________"}, в лице руководителя, действующего на основании Устава, именуемое в дальнейшем «${role2}», с другой стороны,

совместно именуемые «Стороны», а по отдельности «Сторона», заключили ${f.thisNom} ${f.nom} о нижеследующем:`;
}
