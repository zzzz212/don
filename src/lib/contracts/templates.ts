// Genitive form, used after "в течение" / "сроком" — most common context.
const DURATION_LABELS: Record<string, string> = {
  "1": "1 (одного) года",
  "2": "2 (двух) лет",
  "3": "3 (трёх) лет",
  "5": "5 (пяти) лет",
  "6": "6 (шести) месяцев",
  "11": "11 (одиннадцати) месяцев",
  "12": "12 (двенадцати) месяцев",
  "24": "24 (двадцати четырёх) месяцев",
  "36": "36 (тридцати шести) месяцев",
  "60": "60 (шестидесяти) месяцев",
  indefinite: "бессрочно",
};

// Months only — useful for probation periods, warranty in months.
const MONTHS_LABELS: Record<string, string> = {
  "1": "1 (один) месяц",
  "2": "2 (два) месяца",
  "3": "3 (три) месяца",
  "6": "6 (шесть) месяцев",
  "12": "12 (двенадцать) месяцев",
  "24": "24 (двадцать четыре) месяца",
  "60": "60 (шестьдесят) месяцев",
};

function pickMonths(value: string): string {
  return MONTHS_LABELS[value] || `${value} месяцев`;
}

const PAYMENT_LABELS: Record<string, string> = {
  prepaid: "100% (сто процентов) предоплата в течение 5 (пяти) банковских дней с момента подписания настоящего Договора",
  postpaid: "оплата в течение 5 (пяти) банковских дней после подписания акта приёма-передачи",
  partial: "50% (пятьдесят процентов) предоплата, 50% (пятьдесят процентов) — после подписания акта приёма-передачи",
  installments: "рассрочка в соответствии с графиком платежей (Приложение №1 к настоящему Договору)",
  milestone: "поэтапная оплата по завершении каждого этапа работ согласно календарному плану",
};

function pickDuration(value: string): string {
  return DURATION_LABELS[value] || value || "_______________";
}

function pickPayment(value: string): string {
  return PAYMENT_LABELS[value] || "в порядке, согласованном Сторонами";
}

// ──────────────────────────────────────────────────────────────────
// 1. NDA
// ──────────────────────────────────────────────────────────────────
export function generateNDA(d: Data): string {
  const today = todayInWords();
  const penalty = Number(d.penalty || 0);
  const duration = pickDuration(d.duration);

  const nonSolicitClause = d.nonSolicitation && d.nonSolicitation !== "no"
    ? `\n2.4. Получающая сторона обязуется не переманивать сотрудников Раскрывающей стороны в течение ${d.nonSolicitation === "6months" ? "6 (шести) месяцев" : "1 (одного) года"} после прекращения настоящего Соглашения.`
    : "";

  const ipClause = d.ipOwnership
    ? `\n2.5. Все права на интеллектуальную собственность, переданную или созданную в рамках сотрудничества, ${d.ipOwnership === "disclosing" ? "принадлежат Раскрывающей стороне" : d.ipOwnership === "receiving" ? "принадлежат Получающей стороне" : "являются совместной собственностью Сторон"}.`
    : "";

  const returnClause = d.materialsReturn && d.materialsReturn !== "no"
    ? `\n2.6. По письменному требованию Раскрывающей стороны Получающая сторона обязуется в течение 10 (десяти) календарных дней ${d.materialsReturn === "destruction" ? "уничтожить все материалы, содержащие конфиденциальную информацию, и предоставить акт об уничтожении" : "вернуть все материалы, содержащие конфиденциальную информацию"}.`
    : "";

  return `${header("Соглашение о неразглашении конфиденциальной информации", today)}
${preamble(d.disclosingParty, d.disclosingInn, "Раскрывающая сторона", d.receivingParty, d.receivingInn, "Получающая сторона", "Соглашение")}

1. ПРЕДМЕТ СОГЛАШЕНИЯ

1.1. Получающая сторона обязуется не разглашать конфиденциальную информацию, полученную от Раскрывающей стороны, и использовать её исключительно в целях совместного сотрудничества Сторон.

1.2. Под конфиденциальной информацией в настоящем Соглашении понимается:
${d.subject || "сведения, относящиеся к коммерческой деятельности Раскрывающей стороны"}.

1.3. Конфиденциальной не признаётся информация, которая:
   а) на момент её раскрытия являлась общедоступной не вследствие нарушения настоящего Соглашения;
   б) была известна Получающей стороне до её раскрытия Раскрывающей стороной без обязательства о конфиденциальности;
   в) подлежит раскрытию по требованию государственных органов в порядке, установленном законодательством РФ.

2. ОБЯЗАННОСТИ ПОЛУЧАЮЩЕЙ СТОРОНЫ

2.1. Получающая сторона обязуется:
   а) не раскрывать конфиденциальную информацию третьим лицам без письменного согласия Раскрывающей стороны;
   б) использовать конфиденциальную информацию исключительно в целях, определённых настоящим Соглашением;
   в) обеспечить защиту конфиденциальной информации от несанкционированного доступа способами не менее надёжными, чем те, которыми защищается её собственная конфиденциальная информация;
   г) ограничить круг лиц, имеющих доступ к конфиденциальной информации, своими сотрудниками, которым такая информация необходима для выполнения служебных обязанностей;
   д) незамедлительно письменно уведомить Раскрывающую сторону о любом факте несанкционированного доступа к конфиденциальной информации.

2.2. Получающая сторона несёт ответственность за действия своих сотрудников и привлекаемых третьих лиц, имеющих доступ к конфиденциальной информации, как за свои собственные.

2.3. Раскрытие конфиденциальной информации по требованию государственных органов не является нарушением настоящего Соглашения при условии, что Получающая сторона незамедлительно уведомит Раскрывающую сторону о таком требовании.${nonSolicitClause}${ipClause}${returnClause}

3. СРОК ДЕЙСТВИЯ

3.1. Настоящее Соглашение вступает в силу с момента подписания обеими Сторонами и действует в течение ${duration}.

3.2. Обязательства по сохранению конфиденциальности сохраняют силу в течение 3 (трёх) лет после прекращения действия настоящего Соглашения.

4. ОТВЕТСТВЕННОСТЬ

4.1. В случае нарушения условий настоящего Соглашения Получающая сторона обязуется выплатить Раскрывающей стороне штраф в размере ${moneyDisplay(penalty)}.

4.2. Выплата штрафа не освобождает Получающую сторону от обязанности возместить убытки, причинённые разглашением конфиденциальной информации, в полном объёме сверх суммы штрафа.

4.3. Раскрывающая сторона вправе требовать в судебном порядке прекращения противоправных действий и восстановления нарушенных прав.

${forceMajeure(5, "Соглашение")}

${disputeResolution(6, "Соглашение")}

${finalProvisions(7, "Соглашение")}

${signatureBlock("Раскрывающая сторона", d.disclosingParty, "Получающая сторона", d.receivingParty)}`;
}

